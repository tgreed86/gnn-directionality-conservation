class _BaseHeatDataset(Dataset):
    """Base dataset wrapper returning dictionary samples on a fixed periodic grid."""

    def __init__(
        self,
        *,
        x: np.ndarray | torch.Tensor,
        y: np.ndarray | torch.Tensor,
        u_next: np.ndarray | torch.Tensor,
        pos: np.ndarray | torch.Tensor,
        edge_index: np.ndarray | torch.Tensor,
        edge_attr: np.ndarray | torch.Tensor,
        pair_trajectory_id: np.ndarray | torch.Tensor | None = None,
        pair_time_index: np.ndarray | torch.Tensor | None = None,
        rollout_states: np.ndarray | torch.Tensor | None = None,
        metadata: Mapping[str, Any],
        dtype: torch.dtype = torch.float32,
    ) -> None:
        self.x = torch.as_tensor(x, dtype=dtype)
        self.y = torch.as_tensor(y, dtype=dtype)
        self.u_next = torch.as_tensor(u_next, dtype=dtype)
        self.pos = torch.as_tensor(pos, dtype=dtype)
        self.edge_index = torch.as_tensor(edge_index, dtype=torch.long)
        self.edge_attr = torch.as_tensor(edge_attr, dtype=dtype)
        self.pair_trajectory_id = (
            None
            if pair_trajectory_id is None
            else torch.as_tensor(pair_trajectory_id, dtype=torch.long)
        )
        self.pair_time_index = (
            None
            if pair_time_index is None
            else torch.as_tensor(pair_time_index, dtype=torch.long)
        )
        self.rollout_states = (
            None
            if rollout_states is None
            else torch.as_tensor(rollout_states, dtype=dtype)
        )
        self.metadata = dict(metadata)
        self.dtype = dtype
        spatial_dim = int(self.metadata.get("spatial_dim", SPATIAL_DIM_2D))
        if spatial_dim not in SPATIAL_DIMS:
            raise ValueError(
                f"metadata spatial_dim must be one of {sorted(SPATIAL_DIMS)}, "
                f"got {spatial_dim}."
            )

        if self.x.ndim != 3 or self.x.shape[-1] != 1:
            raise ValueError(f"x must have shape [S, N, 1], got {tuple(self.x.shape)}.")
        if self.y.shape != self.x.shape:
            raise ValueError(
                f"y must have same shape as x, got y={tuple(self.y.shape)} "
                f"and x={tuple(self.x.shape)}."
            )
        if self.u_next.shape != self.x.shape:
            raise ValueError(
                "u_next must have same shape as x, got "
                f"u_next={tuple(self.u_next.shape)} and x={tuple(self.x.shape)}."
            )
        if self.pos.shape != (self.x.shape[1], 2):
            raise ValueError(
                "pos must have shape [N, 2], got "
                f"{tuple(self.pos.shape)} for N={self.x.shape[1]}."
            )
        if self.edge_index.ndim != 2 or self.edge_index.shape[0] != 2:
            raise ValueError(
                f"edge_index must have shape [2, E], got {tuple(self.edge_index.shape)}."
            )
        expected_edges = (
            2 * int(self.x.shape[1])
            if spatial_dim == SPATIAL_DIM_1D
            else 4 * int(self.x.shape[1])
        )
        if self.edge_index.shape[1] != expected_edges:
            raise ValueError(
                "edge_index has the wrong number of edges for "
                f"spatial_dim={spatial_dim}: expected {expected_edges}, "
                f"got {self.edge_index.shape[1]}."
            )
        if self.edge_attr.shape[0] != self.edge_index.shape[1]:
            raise ValueError(
                "edge_attr first dimension must match edge_index edge count, "
                f"got {self.edge_attr.shape[0]} vs {self.edge_index.shape[1]}."
            )
        if self.pair_trajectory_id is not None:
            if self.pair_trajectory_id.shape != (self.x.shape[0],):
                raise ValueError(
                    "pair_trajectory_id must have shape [S], got "
                    f"{tuple(self.pair_trajectory_id.shape)} for S={self.x.shape[0]}."
                )
        if self.pair_time_index is not None:
            if self.pair_time_index.shape != (self.x.shape[0],):
                raise ValueError(
                    "pair_time_index must have shape [S], got "
                    f"{tuple(self.pair_time_index.shape)} for S={self.x.shape[0]}."
                )
        if self.rollout_states is not None:
            if self.rollout_states.ndim != 4 or self.rollout_states.shape[-1] != 1:
                raise ValueError(
                    "rollout_states must have shape [num_samples, window+1, N, 1], "
                    f"got {tuple(self.rollout_states.shape)}."
                )
            if self.rollout_states.shape[2] != self.x.shape[1]:
                raise ValueError(
                    "rollout_states N dimension must match pair N dimension, got "
                    f"{self.rollout_states.shape[2]} vs {self.x.shape[1]}."
                )

    def __len__(self) -> int:
        return int(self.x.shape[0])

    def __getitem__(self, idx: int) -> Dict[str, Any]:
        sample_id = (
            int(self.pair_trajectory_id[idx].item())
            if self.pair_trajectory_id is not None
            else int(idx)
        )
        time_index = (
            int(self.pair_time_index[idx].item())
            if self.pair_time_index is not None
            else 0
        )
        return {
            "x": self.x[idx],
            "y": self.y[idx],
            "u_next": self.u_next[idx],
            "pos": self.pos,
            "edge_index": self.edge_index,
            "edge_attr": self.edge_attr,
            "dt": float(self.metadata["dt"]),
            "dx": float(self.metadata["dx"]),
            "dy": float(self.metadata["dy"]),
            "nu": float(self.metadata["nu"]),
            "Lx": float(self.metadata["Lx"]),
            "Ly": float(self.metadata["Ly"]),
            "nx": int(self.metadata["nx"]),
            "ny": int(self.metadata["ny"]),
            "spatial_dim": int(self.metadata.get("spatial_dim", SPATIAL_DIM_2D)),
            "sample_id": sample_id,
            "pair_index": int(idx),
            "time_index": time_index,
        }


class PeriodicHeatDataset(_BaseHeatDataset):
    """Generate supervised data for 1D or 2D periodic heat diffusion."""

    def __init__(
        self,
        *,
        nx: int = 32,
        ny: int = 32,
        spatial_dim: int = SPATIAL_DIM_2D,
        Lx: float = 1.0,
        Ly: float = 1.0,
        nu: float = 0.01,
        CFL: float = 0.2,
        num_samples: int = 1000,
        m_max_x: int = 8,
        m_max_y: int = 8,
        amplitude: float = 1.0,
        spectral_decay: float = 1.0,
        target_type: str = TARGET_TYPE_RATE,
        window: int = 1,
        seed: int = 1234,
        normalize_rms: Optional[float] = None,
        dtype: torch.dtype = torch.float32,
    ) -> None:
        if target_type not in TARGET_TYPES:
            raise ValueError(
                f"target_type must be one of {sorted(TARGET_TYPES)}, got '{target_type}'."
            )
        if window < 1:
            raise ValueError(f"window must be >= 1, got {window}.")
        spatial_dim = int(spatial_dim)
        if spatial_dim not in SPATIAL_DIMS:
            raise ValueError(
                f"spatial_dim must be one of {sorted(SPATIAL_DIMS)}, "
                f"got {spatial_dim}."
            )

        rng = np.random.default_rng(seed)
        if spatial_dim == SPATIAL_DIM_1D:
            dx, dt = compute_dx_dt(nx=nx, Lx=Lx, nu=nu, CFL=CFL)
            dy = 0.0
            ny_used = 1
            m_max_y_used = 0
            u0 = generate_random_periodic_ic_1d(
                num_samples=num_samples,
                nx=nx,
                Lx=Lx,
                m_max_x=m_max_x,
                amplitude=amplitude,
                spectral_decay=spectral_decay,
                rng=rng,
                normalize_rms=normalize_rms,
            )

            # [num_samples, window+1, nx]
            rollout = np.empty((num_samples, window + 1, nx), dtype=np.float64)
            rollout[:, 0, :] = u0
            for t in range(window):
                rollout[:, t + 1, :] = exact_heat_spectral_step_1d(
                    rollout[:, t, :],
                    nu=nu,
                    dt=dt,
                    Lx=Lx,
                )

            n_nodes = int(nx)
            x_coords = np.arange(nx, dtype=np.float64) * float(dx)
            pos = np.stack([x_coords, np.zeros_like(x_coords)], axis=1)
            edge_index, edge_attr = build_periodic_line_graph(
                nx=nx,
                dx=dx,
                dtype=dtype,
            )
        else:
            dx, dy, dt = compute_dx_dy_dt(
                nx=nx,
                ny=ny,
                Lx=Lx,
                Ly=Ly,
                nu=nu,
                CFL=CFL,
            )
            ny_used = int(ny)
            m_max_y_used = int(m_max_y)
            u0 = generate_random_periodic_ic_2d(
                num_samples=num_samples,
                nx=nx,
                ny=ny,
                Lx=Lx,
                Ly=Ly,
                m_max_x=m_max_x,
                m_max_y=m_max_y,
                amplitude=amplitude,
                spectral_decay=spectral_decay,
                rng=rng,
                normalize_rms=normalize_rms,
            )

            # [num_samples, window+1, nx, ny]
            rollout = np.empty((num_samples, window + 1, nx, ny), dtype=np.float64)
            rollout[:, 0, :, :] = u0
            for t in range(window):
                rollout[:, t + 1, :, :] = exact_heat_spectral_step(
                    rollout[:, t, :, :],
                    nu=nu,
                    dt=dt,
                    Lx=Lx,
                    Ly=Ly,
                )

            n_nodes = int(nx * ny)
            x_coords = np.arange(nx, dtype=np.float64) * float(dx)
            y_coords = np.arange(ny, dtype=np.float64) * float(dy)
            gx, gy = np.meshgrid(x_coords, y_coords, indexing="ij")
            pos = np.stack([gx.reshape(-1), gy.reshape(-1)], axis=1)
            edge_index, edge_attr = build_periodic_grid_graph(
                nx=nx,
                ny=ny,
                dx=dx,
                dy=dy,
                dtype=dtype,
            )

        u_now_pairs = rollout[:, :-1, ...]
        u_next_pairs = rollout[:, 1:, ...]
        num_pairs = int(num_samples * window)

        u_now = u_now_pairs.reshape(num_pairs, n_nodes)
        u_next = u_next_pairs.reshape(num_pairs, n_nodes)
        pair_trajectory_id = np.repeat(np.arange(num_samples, dtype=np.int64), window)
        pair_time_index = np.tile(np.arange(window, dtype=np.int64), num_samples)

        if target_type == TARGET_TYPE_NEXT:
            y = u_next
        else:
            y = (u_next - u_now) / float(dt)

        x = u_now[..., None]
        y = y[..., None]
        u_next = u_next[..., None]
        rollout_states = rollout.reshape(num_samples, window + 1, n_nodes)[..., None]

        metadata = HeatMetadata(
            spatial_dim=int(spatial_dim),
            nx=int(nx),
            ny=int(ny_used),
            N=int(n_nodes),
            Lx=float(Lx),
            Ly=float(Ly),
            nu=float(nu),
            CFL=float(CFL),
            dt=float(dt),
            dx=float(dx),
            dy=float(dy),
            m_max_x=int(m_max_x),
            m_max_y=int(m_max_y_used),
            amplitude=float(amplitude),
            spectral_decay=float(spectral_decay),
            target_type=target_type,
            seed=int(seed),
            num_samples=int(num_samples),
            window=int(window),
            num_pairs=int(num_pairs),
            normalize_rms=float(np.nan if normalize_rms is None else normalize_rms),
        ).to_dict()

        super().__init__(
            x=x,
            y=y,
            u_next=u_next,
            pos=pos,
            edge_index=edge_index,
            edge_attr=edge_attr,
            pair_trajectory_id=pair_trajectory_id,
            pair_time_index=pair_time_index,
            rollout_states=rollout_states,
            metadata=metadata,
            dtype=dtype,
        )


class LoadedHeatDataset(_BaseHeatDataset):
    """Dataset loaded from saved `.npz` arrays and metadata."""


def save_heat_dataset(dataset: _BaseHeatDataset, out_path: str | Path) -> None:
    """Save arrays and metadata to compressed `.npz`."""
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    meta = dataset.metadata
    np.savez_compressed(
        out_path,
        x=dataset.x.cpu().numpy(),
        y=dataset.y.cpu().numpy(),
        u_next=dataset.u_next.cpu().numpy(),
        pos=dataset.pos.cpu().numpy(),
        edge_index=dataset.edge_index.cpu().numpy(),
        edge_attr=dataset.edge_attr.cpu().numpy(),
        pair_trajectory_id=(
            np.array([], dtype=np.int64)
            if dataset.pair_trajectory_id is None
            else dataset.pair_trajectory_id.cpu().numpy()
        ),
        pair_time_index=(
            np.array([], dtype=np.int64)
            if dataset.pair_time_index is None
            else dataset.pair_time_index.cpu().numpy()
        ),
        rollout_states=(
            np.array([], dtype=np.float32)
            if dataset.rollout_states is None
            else dataset.rollout_states.cpu().numpy()
        ),
        spatial_dim=np.int64(meta.get("spatial_dim", SPATIAL_DIM_2D)),
        nx=np.int64(meta["nx"]),
        ny=np.int64(meta["ny"]),
        N=np.int64(meta["N"]),
        Lx=np.float64(meta["Lx"]),
        Ly=np.float64(meta["Ly"]),
        nu=np.float64(meta["nu"]),
        CFL=np.float64(meta["CFL"]),
        dt=np.float64(meta["dt"]),
        dx=np.float64(meta["dx"]),
        dy=np.float64(meta["dy"]),
        m_max_x=np.int64(meta["m_max_x"]),
        m_max_y=np.int64(meta["m_max_y"]),
        amplitude=np.float64(meta["amplitude"]),
        spectral_decay=np.float64(meta["spectral_decay"]),
        target_type=np.array(str(meta["target_type"])),
        seed=np.int64(meta["seed"]),
        num_samples=np.int64(meta["num_samples"]),
        window=np.int64(meta.get("window", 1)),
        num_pairs=np.int64(meta.get("num_pairs", int(dataset.x.shape[0]))),
        normalize_rms=np.float64(meta.get("normalize_rms", np.nan)),
    )


def load_heat_dataset(
    path: str | Path,
    *,
    dtype: torch.dtype = torch.float32,
) -> LoadedHeatDataset:
    """Load dataset arrays + metadata from `.npz`."""
    path = Path(path)
    with np.load(path) as data:
        window = int(data["window"].item()) if "window" in data.files else 1
        num_pairs = (
            int(data["num_pairs"].item())
            if "num_pairs" in data.files
            else int(data["x"].shape[0])
        )

        nx = int(data["nx"].item())
        ny = int(data["ny"].item())
        n_default = int(nx * ny)
        spatial_dim = (
            int(data["spatial_dim"].item())
            if "spatial_dim" in data.files
            else SPATIAL_DIM_2D
        )

        metadata = {
            "spatial_dim": spatial_dim,
            "nx": nx,
            "ny": ny,
            "N": int(data["N"].item()) if "N" in data.files else n_default,
            "Lx": float(data["Lx"].item()),
            "Ly": float(data["Ly"].item()),
            "nu": float(data["nu"].item()),
            "CFL": float(data["CFL"].item()),
            "dt": float(data["dt"].item()),
            "dx": float(data["dx"].item()),
            "dy": float(data["dy"].item()),
            "m_max_x": int(data["m_max_x"].item()),
            "m_max_y": int(data["m_max_y"].item()),
            "amplitude": float(data["amplitude"].item()),
            "spectral_decay": float(data["spectral_decay"].item()),
            "target_type": str(data["target_type"].item()),
            "seed": int(data["seed"].item()),
            "num_samples": int(data["num_samples"].item()),
            "window": int(window),
            "num_pairs": int(num_pairs),
            "normalize_rms": float(data["normalize_rms"].item()),
        }

        pair_trajectory_id = None
        if "pair_trajectory_id" in data.files and data["pair_trajectory_id"].size > 0:
            pair_trajectory_id = data["pair_trajectory_id"]

        pair_time_index = None
        if "pair_time_index" in data.files and data["pair_time_index"].size > 0:
            pair_time_index = data["pair_time_index"]

        rollout_states = None
        if "rollout_states" in data.files and data["rollout_states"].size > 0:
            rollout_states = data["rollout_states"]

        dataset = LoadedHeatDataset(
            x=data["x"],
            y=data["y"],
            u_next=data["u_next"],
            pos=data["pos"],
            edge_index=data["edge_index"],
            edge_attr=data["edge_attr"],
            pair_trajectory_id=pair_trajectory_id,
            pair_time_index=pair_time_index,
            rollout_states=rollout_states,
            metadata=metadata,
            dtype=dtype,
        )
    return dataset
