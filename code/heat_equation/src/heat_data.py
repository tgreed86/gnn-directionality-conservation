"""Training-data generator for periodic heat-equation datasets.

This module builds supervised one-step pairs for either the 1D equation

    u_t = nu * u_xx

or the 2D equation

    u_t = nu * (u_xx + u_yy)

on a periodic interval or rectangular domain. Labels are generated by exact
spectral evolution in Fourier space.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, Mapping, Optional, Tuple

import numpy as np
import torch
from torch.utils.data import Dataset

TARGET_TYPE_NEXT = "next"
TARGET_TYPE_RATE = "rate"
TARGET_TYPES = {TARGET_TYPE_NEXT, TARGET_TYPE_RATE}
SPATIAL_DIM_1D = 1
SPATIAL_DIM_2D = 2
SPATIAL_DIMS = {SPATIAL_DIM_1D, SPATIAL_DIM_2D}


def compute_dx_dt(
    nx: int,
    Lx: float,
    nu: float,
    CFL: float,
) -> Tuple[float, float]:
    """Compute 1D grid spacing and time step from a diffusion CFL-like number."""
    if nx <= 1:
        raise ValueError(f"nx must be > 1, got {nx}.")
    if Lx <= 0.0:
        raise ValueError(f"Lx must be positive, got {Lx}.")
    if nu <= 0.0:
        raise ValueError(f"nu must be positive, got {nu}.")
    if CFL <= 0.0:
        raise ValueError(f"CFL must be positive, got {CFL}.")

    dx = float(Lx) / float(nx)
    dt = float(CFL) * dx**2 / float(nu)
    return dx, dt


def compute_dx_dy_dt(
    nx: int,
    ny: int,
    Lx: float,
    Ly: float,
    nu: float,
    CFL: float,
) -> Tuple[float, float, float]:
    """Compute grid spacings and time step from a diffusion CFL-like number.

    We define
      dt = CFL * min(dx, dy)^2 / nu

    which mirrors the familiar explicit diffusion scaling, even though label
    generation here uses exact spectral stepping.
    """
    if nx <= 1:
        raise ValueError(f"nx must be > 1, got {nx}.")
    if ny <= 1:
        raise ValueError(f"ny must be > 1, got {ny}.")
    if Lx <= 0.0:
        raise ValueError(f"Lx must be positive, got {Lx}.")
    if Ly <= 0.0:
        raise ValueError(f"Ly must be positive, got {Ly}.")
    if nu <= 0.0:
        raise ValueError(f"nu must be positive, got {nu}.")
    if CFL <= 0.0:
        raise ValueError(f"CFL must be positive, got {CFL}.")

    dx = float(Lx) / float(nx)
    dy = float(Ly) / float(ny)
    dt = float(CFL) * min(dx, dy) ** 2 / float(nu)
    return dx, dy, dt


def _node_id(ix: int, iy: int, ny: int) -> int:
    return int(ix) * int(ny) + int(iy)


def build_periodic_line_graph(
    nx: int,
    *,
    dx: float = 1.0,
    dtype: torch.dtype = torch.float32,
    include_physical_displacement: bool = False,
    include_distance: bool = False,
) -> Tuple[torch.LongTensor, torch.Tensor]:
    """Build directed 2-neighbor periodic line graph.

    Each node has outgoing edges to its right and left neighbors.

    Returns:
        edge_index: LongTensor [2, 2N]
        edge_attr: Tensor [2N, D], where the first channel is normalized
            signed displacement dx_ij / dx.
    """
    if nx <= 1:
        raise ValueError(f"nx must be > 1, got {nx}.")
    if dx <= 0.0:
        raise ValueError(f"dx must be positive, got {dx}.")

    n_edges = int(2 * nx)
    sources = np.empty((n_edges,), dtype=np.int64)
    targets = np.empty((n_edges,), dtype=np.int64)
    disp_norm = np.empty((n_edges, 1), dtype=np.float64)

    k = 0
    for ix in range(nx):
        sources[k] = ix
        targets[k] = (ix + 1) % nx
        disp_norm[k, 0] = 1.0
        k += 1

        sources[k] = ix
        targets[k] = (ix - 1) % nx
        disp_norm[k, 0] = -1.0
        k += 1

    edge_index = torch.tensor(
        np.stack([sources, targets], axis=0), dtype=torch.long
    )

    attrs = [disp_norm]
    if include_physical_displacement:
        attrs.append(disp_norm * float(dx))
    if include_distance:
        attrs.append(np.full((n_edges, 1), float(dx), dtype=np.float64))

    edge_attr = torch.tensor(np.concatenate(attrs, axis=1), dtype=dtype)
    return edge_index, edge_attr


def build_periodic_grid_graph(
    nx: int,
    ny: int,
    *,
    dx: float = 1.0,
    dy: float = 1.0,
    dtype: torch.dtype = torch.float32,
    include_physical_displacement: bool = False,
    include_distance: bool = False,
) -> Tuple[torch.LongTensor, torch.Tensor]:
    """Build directed 4-neighbor periodic grid graph.

    Each node has outgoing edges to east/west/north/south neighbors.

    Returns:
        edge_index: LongTensor [2, 4N]
        edge_attr: Tensor [4N, D], where first two channels are normalized
            signed displacement [dx_ij / dx, dy_ij / dy].
    """
    if nx <= 1:
        raise ValueError(f"nx must be > 1, got {nx}.")
    if ny <= 1:
        raise ValueError(f"ny must be > 1, got {ny}.")
    if dx <= 0.0:
        raise ValueError(f"dx must be positive, got {dx}.")
    if dy <= 0.0:
        raise ValueError(f"dy must be positive, got {dy}.")

    n_nodes = int(nx * ny)
    n_edges = int(4 * n_nodes)

    sources = np.empty((n_edges,), dtype=np.int64)
    targets = np.empty((n_edges,), dtype=np.int64)
    disp_norm = np.empty((n_edges, 2), dtype=np.float64)

    k = 0
    for ix in range(nx):
        for iy in range(ny):
            src = _node_id(ix, iy, ny)

            # East
            sources[k] = src
            targets[k] = _node_id((ix + 1) % nx, iy, ny)
            disp_norm[k, :] = (1.0, 0.0)
            k += 1

            # West
            sources[k] = src
            targets[k] = _node_id((ix - 1) % nx, iy, ny)
            disp_norm[k, :] = (-1.0, 0.0)
            k += 1

            # North
            sources[k] = src
            targets[k] = _node_id(ix, (iy + 1) % ny, ny)
            disp_norm[k, :] = (0.0, 1.0)
            k += 1

            # South
            sources[k] = src
            targets[k] = _node_id(ix, (iy - 1) % ny, ny)
            disp_norm[k, :] = (0.0, -1.0)
            k += 1

    edge_index = torch.tensor(
        np.stack([sources, targets], axis=0), dtype=torch.long
    )

    attrs = [disp_norm]
    if include_physical_displacement:
        disp_phys = np.empty_like(disp_norm)
        disp_phys[:, 0] = disp_norm[:, 0] * float(dx)
        disp_phys[:, 1] = disp_norm[:, 1] * float(dy)
        attrs.append(disp_phys)
    if include_distance:
        dist = np.sqrt((disp_norm[:, 0] * dx) ** 2 + (disp_norm[:, 1] * dy) ** 2)
        attrs.append(dist[:, None])

    edge_attr = torch.tensor(np.concatenate(attrs, axis=1), dtype=dtype)
    return edge_index, edge_attr


def exact_heat_spectral_step_1d(
    u: np.ndarray,
    *,
    nu: float,
    dt: float,
    Lx: float,
) -> np.ndarray:
    """Advance periodic 1D field by exact Fourier heat-equation evolution."""
    u_arr = np.asarray(u, dtype=np.float64)
    if u_arr.ndim < 1:
        raise ValueError("u must have at least 1 dimension with final axis [nx].")

    nx = int(u_arr.shape[-1])
    if nx <= 1:
        raise ValueError("u final axis must be > 1.")
    if Lx <= 0.0:
        raise ValueError("Lx must be positive.")
    if nu <= 0.0:
        raise ValueError("nu must be positive.")

    dx = float(Lx) / float(nx)
    kx = 2.0 * np.pi * np.fft.fftfreq(nx, d=dx)
    decay = np.exp(-float(nu) * (kx**2) * float(dt))
    u_hat = np.fft.fft(u_arr, axis=-1)
    u_next = np.fft.ifft(u_hat * decay, axis=-1).real
    return u_next


def exact_heat_spectral_step(
    u: np.ndarray,
    *,
    nu: float,
    dt: float,
    Lx: float,
    Ly: float,
) -> np.ndarray:
    """Advance periodic 2D field by exact Fourier heat-equation evolution."""
    u_arr = np.asarray(u, dtype=np.float64)
    if u_arr.ndim < 2:
        raise ValueError("u must have at least 2 dimensions with final axes [nx, ny].")

    nx = int(u_arr.shape[-2])
    ny = int(u_arr.shape[-1])
    if nx <= 1 or ny <= 1:
        raise ValueError("u final axes must both be > 1.")
    if Lx <= 0.0 or Ly <= 0.0:
        raise ValueError("Lx and Ly must be positive.")
    if nu <= 0.0:
        raise ValueError("nu must be positive.")

    dx = float(Lx) / float(nx)
    dy = float(Ly) / float(ny)
    kx = 2.0 * np.pi * np.fft.fftfreq(nx, d=dx)
    ky = 2.0 * np.pi * np.fft.fftfreq(ny, d=dy)
    k2 = (kx[:, None] ** 2) + (ky[None, :] ** 2)

    decay = np.exp(-float(nu) * k2 * float(dt))
    u_hat = np.fft.fftn(u_arr, axes=(-2, -1))
    u_next = np.fft.ifftn(u_hat * decay, axes=(-2, -1)).real
    return u_next


def generate_random_periodic_ic_1d(
    *,
    num_samples: int,
    nx: int,
    Lx: float,
    m_max_x: int,
    amplitude: float,
    spectral_decay: float,
    rng: np.random.Generator,
    normalize_rms: Optional[float] = None,
) -> np.ndarray:
    """Generate smooth random periodic 1D initial conditions."""
    if num_samples <= 0:
        raise ValueError(f"num_samples must be positive, got {num_samples}.")
    if nx <= 1:
        raise ValueError(f"nx must be > 1, got {nx}.")
    if Lx <= 0.0:
        raise ValueError("Lx must be positive.")
    if m_max_x < 1:
        raise ValueError(f"m_max_x must be >= 1, got {m_max_x}.")
    if amplitude < 0.0:
        raise ValueError(f"amplitude must be non-negative, got {amplitude}.")
    if spectral_decay < 0.0:
        raise ValueError(
            f"spectral_decay must be non-negative, got {spectral_decay}."
        )
    if normalize_rms is not None and normalize_rms <= 0.0:
        raise ValueError(
            f"normalize_rms must be positive when provided, got {normalize_rms}."
        )

    x = np.arange(nx, dtype=np.float64) * (float(Lx) / float(nx))
    mx = np.arange(1, m_max_x + 1, dtype=np.float64)
    phase_x = (2.0 * np.pi / float(Lx)) * np.outer(mx, x)

    sinx = np.sin(phase_x)
    cosx = np.cos(phase_x)
    coeff_scale = float(amplitude) / np.power(mx, float(spectral_decay))

    a_s = rng.standard_normal(size=(num_samples, m_max_x)) * coeff_scale[None, :]
    a_c = rng.standard_normal(size=(num_samples, m_max_x)) * coeff_scale[None, :]

    u = np.einsum("sm,mx->sx", a_s, sinx)
    u += np.einsum("sm,mx->sx", a_c, cosx)

    if normalize_rms is not None:
        rms = np.sqrt(np.mean(u**2, axis=1, keepdims=True))
        safe_rms = np.maximum(rms, 1e-14)
        u = u * (float(normalize_rms) / safe_rms)

    return u


def generate_random_periodic_ic_2d(
    *,
    num_samples: int,
    nx: int,
    ny: int,
    Lx: float,
    Ly: float,
    m_max_x: int,
    m_max_y: int,
    amplitude: float,
    spectral_decay: float,
    rng: np.random.Generator,
    normalize_rms: Optional[float] = None,
) -> np.ndarray:
    """Generate smooth random periodic 2D initial conditions.

    Construction:
      u(x,y) = sum_{mx=1..m_max_x} sum_{my=1..m_max_y}
                 coeff(mx,my) * basis(mx,my; x,y)

    with basis terms from sin/cos products and coefficient scale
      amplitude / (mx^2 + my^2)^(spectral_decay/2).
    """
    if num_samples <= 0:
        raise ValueError(f"num_samples must be positive, got {num_samples}.")
    if nx <= 1:
        raise ValueError(f"nx must be > 1, got {nx}.")
    if ny <= 1:
        raise ValueError(f"ny must be > 1, got {ny}.")
    if Lx <= 0.0 or Ly <= 0.0:
        raise ValueError("Lx and Ly must be positive.")
    if m_max_x < 1:
        raise ValueError(f"m_max_x must be >= 1, got {m_max_x}.")
    if m_max_y < 1:
        raise ValueError(f"m_max_y must be >= 1, got {m_max_y}.")
    if amplitude < 0.0:
        raise ValueError(f"amplitude must be non-negative, got {amplitude}.")
    if spectral_decay < 0.0:
        raise ValueError(
            f"spectral_decay must be non-negative, got {spectral_decay}."
        )
    if normalize_rms is not None and normalize_rms <= 0.0:
        raise ValueError(
            f"normalize_rms must be positive when provided, got {normalize_rms}."
        )

    x = np.arange(nx, dtype=np.float64) * (float(Lx) / float(nx))
    y = np.arange(ny, dtype=np.float64) * (float(Ly) / float(ny))

    mx = np.arange(1, m_max_x + 1, dtype=np.float64)
    my = np.arange(1, m_max_y + 1, dtype=np.float64)

    phase_x = (2.0 * np.pi / float(Lx)) * np.outer(mx, x)  # [mx, nx]
    phase_y = (2.0 * np.pi / float(Ly)) * np.outer(my, y)  # [my, ny]

    sinx = np.sin(phase_x)
    cosx = np.cos(phase_x)
    siny = np.sin(phase_y)
    cosy = np.cos(phase_y)

    k2 = (mx[:, None] ** 2) + (my[None, :] ** 2)
    coeff_scale = float(amplitude) / np.power(k2, float(spectral_decay) / 2.0)

    a_ss = rng.standard_normal(size=(num_samples, m_max_x, m_max_y)) * coeff_scale[None, :, :]
    a_sc = rng.standard_normal(size=(num_samples, m_max_x, m_max_y)) * coeff_scale[None, :, :]
    a_cs = rng.standard_normal(size=(num_samples, m_max_x, m_max_y)) * coeff_scale[None, :, :]
    a_cc = rng.standard_normal(size=(num_samples, m_max_x, m_max_y)) * coeff_scale[None, :, :]

    u = np.einsum("smn,mx,ny->sxy", a_ss, sinx, siny)
    u += np.einsum("smn,mx,ny->sxy", a_sc, sinx, cosy)
    u += np.einsum("smn,mx,ny->sxy", a_cs, cosx, siny)
    u += np.einsum("smn,mx,ny->sxy", a_cc, cosx, cosy)

    if normalize_rms is not None:
        rms = np.sqrt(np.mean(u**2, axis=(1, 2), keepdims=True))
        safe_rms = np.maximum(rms, 1e-14)
        u = u * (float(normalize_rms) / safe_rms)

    return u


