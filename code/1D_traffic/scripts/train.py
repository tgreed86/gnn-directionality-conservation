class LWRGraphPairDataset(torch.utils.data.Dataset):
    """Lazy PyG dataset for rollout windows on a shared fixed graph."""

    def __init__(
        self,
        *,
        x: np.ndarray,
        target: np.ndarray,
        u_next: np.ndarray,
        pair_indices: np.ndarray,
        edge_index: Tensor,
        edge_attr: Tensor,
        trajectory_edge_attr: Optional[np.ndarray],
        pair_trajectory_id: np.ndarray,
        pair_time_index: Optional[np.ndarray],
        interface_flux_rates: Optional[np.ndarray],
        target_type: str,
        static_features: Tensor,
        pair_conditioning: np.ndarray,
        pair_v_max: np.ndarray,
        normalization: Normalization,
        cell_lengths: Tensor,
        dt: float,
        rho_max: float,
        ground_truth_advection: Optional[np.ndarray] = None,
        advection_metadata_by_trajectory: Optional[
            Dict[int, LWRAdvectionMetadata]
        ] = None,
        include_advection_metadata: bool = False,
        rollout_steps: int = 1,
    ) -> None:
        if rollout_steps <= 0:
            raise ValueError("rollout_steps must be positive.")
        self.x = x
        self.target = target
        self.u_next = u_next
        candidate_pair_indices = np.asarray(pair_indices, dtype=np.int64)
        self.edge_index = edge_index
        self.edge_attr = edge_attr
        self.trajectory_edge_attr = trajectory_edge_attr
        self.pair_trajectory_id = np.asarray(
            pair_trajectory_id, dtype=np.int64
        )
        self.pair_time_index = (
            None
            if pair_time_index is None
            else np.asarray(pair_time_index, dtype=np.int64)
        )
        self.interface_flux_rates = interface_flux_rates
        self.target_type = canonical_target_type(target_type)
        self.rollout_steps = int(rollout_steps)
        self.static_features = static_features
        self.pair_conditioning = pair_conditioning
        self.pair_v_max = np.asarray(pair_v_max, dtype=np.float32)
        if self.pair_v_max.shape != (self.x.shape[0],):
            raise ValueError("pair_v_max must have shape [pair].")
        self.normalization = normalization
        self.cell_lengths = cell_lengths.view(-1, 1)
        self.dt_node = torch.full(
            (cell_lengths.numel(), 1),
            float(dt),
            dtype=torch.float32,
        )
        self.rho_max_node = torch.full(
            (cell_lengths.numel(), 1),
            float(rho_max),
            dtype=torch.float32,
        )
        self.ground_truth_advection = ground_truth_advection
        if (
            self.ground_truth_advection is not None
            and self.ground_truth_advection.shape != self.x.shape
        ):
            raise ValueError(
                "ground_truth_advection must have the same shape as x."
            )
        self.advection_metadata_by_trajectory = (
            advection_metadata_by_trajectory
        )
        self.include_advection_metadata = bool(
            include_advection_metadata
        )
        if (
            self.include_advection_metadata
            and self.advection_metadata_by_trajectory is None
        ):
            raise ValueError(
                "include_advection_metadata requires cached metadata."
            )
        self._pair_lookup: Optional[Dict[Tuple[int, int], int]] = None
        if self.rollout_steps > 1:
            if self.pair_time_index is None:
                raise ValueError(
                    "Multi-step rollout training requires pair_time_index."
                )
            self._pair_lookup = {}
            for pair_index, (trajectory_id, time_index) in enumerate(
                zip(self.pair_trajectory_id, self.pair_time_index)
            ):
                key = (int(trajectory_id), int(time_index))
                if key in self._pair_lookup:
                    raise ValueError(
                        "pair trajectory/time metadata contains duplicates."
                    )
                self._pair_lookup[key] = pair_index
            eligible = []
            for pair_index in candidate_pair_indices:
                trajectory_id = int(self.pair_trajectory_id[pair_index])
                time_index = int(self.pair_time_index[pair_index])
                if all(
                    (trajectory_id, time_index + offset)
                    in self._pair_lookup
                    for offset in range(self.rollout_steps)
                ):
                    eligible.append(int(pair_index))
            self.pair_indices = np.asarray(eligible, dtype=np.int64)
            if self.pair_indices.size == 0:
                raise ValueError(
                    "No fixed-topology training windows are long enough for "
                    f"rollout_steps={self.rollout_steps}."
                )
        else:
            self.pair_indices = candidate_pair_indices

    def __len__(self) -> int:
        return int(self.pair_indices.size)

    def __getitem__(self, item: int) -> Data:
        pair_index = int(self.pair_indices[item])
        trajectory_id = int(self.pair_trajectory_id[pair_index])
        if self.rollout_steps == 1:
            future_pair_indices = [pair_index]
        else:
            if self.pair_time_index is None or self._pair_lookup is None:
                raise RuntimeError("Multi-step pair metadata is unavailable.")
            time_index = int(self.pair_time_index[pair_index])
            future_pair_indices = [
                self._pair_lookup[(trajectory_id, time_index + offset)]
                for offset in range(self.rollout_steps)
            ]
        current = torch.from_numpy(self.x[pair_index])
        raw_target = torch.from_numpy(self.target[pair_index])
        next_state = torch.from_numpy(self.u_next[pair_index])
        future_state = torch.from_numpy(
            np.stack(
                [self.u_next[index] for index in future_pair_indices],
                axis=1,
            )
        )

        density = (
            current - self.normalization.density_mean
        ) / self.normalization.density_std
        conditioning = torch.from_numpy(
            self.pair_conditioning[pair_index]
        ).view(1, -1)
        conditioning = conditioning.expand(current.shape[0], -1)
        features = torch.cat(
            (density, self.static_features, conditioning), dim=-1
        )
        target = (
            raw_target - self.normalization.target_mean
        ) / self.normalization.target_std
        edge_attr = self.edge_attr
        if self.trajectory_edge_attr is not None:
            edge_attr = torch.from_numpy(
                self.trajectory_edge_attr[trajectory_id]
            )
        attributes = dict(
            x=features,
            edge_index=self.edge_index,
            edge_attr=edge_attr,
            y=target,
            current=current,
            next_state=next_state,
            future_state=future_state,
            cell_length=self.cell_lengths,
            dt_node=self.dt_node,
            v_max_node=torch.full_like(
                self.cell_lengths,
                float(self.pair_v_max[pair_index]),
            ),
            rho_max_node=self.rho_max_node,
        )
        if self.ground_truth_advection is not None:
            attributes["ground_truth_advection"] = torch.from_numpy(
                self.ground_truth_advection[pair_index]
            )
            if self.include_advection_metadata:
                metadata = self.advection_metadata_by_trajectory[
                    trajectory_id
                ]
                attributes.update(
                    advection_edge_index=metadata.edge_index,
                    advection_junction_attr=metadata.junction_attr,
                )
        if self.interface_flux_rates is not None:
            if self.pair_time_index is None:
                raise RuntimeError(
                    "Flux targets require pair_time_index metadata."
                )
            flux_targets = torch.from_numpy(
                np.stack(
                    [
                        self.interface_flux_rates[
                            trajectory_id,
                            int(self.pair_time_index[index]),
                        ]
                        for index in future_pair_indices
                    ],
                    axis=1,
                )
            )
            if self.target_type == "increment":
                flux_targets = flux_targets * float(self.dt_node[0, 0])
            attributes["flux_target"] = flux_targets[:, 0]
            attributes["future_flux_target"] = flux_targets
        return Data(**attributes)


