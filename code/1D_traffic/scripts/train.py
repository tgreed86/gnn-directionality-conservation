#!/usr/bin/env python3
"""Train a configurable GNN model on fixed or variable LWR data.

The ``--data`` path may be either a fixed-topology ``.npz`` generated by
``generate_network_lwr_traffic_data.py`` or a directory generated by
``generate_variable_network_lwr_traffic_data.py`` or
``generate_structured_directional_lwr_traffic_data.py``. Fixed-topology
datasets are split by trajectory. Directory datasets use the
topology-disjoint splits stored in ``manifest.json``.

SAGEConv, MeshGraphNet, and FluxGraphNet use the stored bidirectional
``edge_index``. FluxGraphNet additionally uses the stored physical-interface
edge attributes to decode one conservative flux per interface. For an
increment target its decoder represents integrated per-step transport; for a
rate target it represents physical flux rate.
Variable-topology junction parameters and optional trajectory flow direction
are supplied through the generator's local node-conditioning and edge
features. Variable graphs use fixed-width, topology-independent
representations and can therefore be batched together by PyTorch Geometric.

Example:

    python scripts/train.py \
        --config config_lwr.json

Values passed directly on the command line override values from the config:

    python scripts/train.py \
        --config config_lwr.json \
        --epochs 50 \
        --learning-rate 5e-4

The output directory contains ``checkpoint.pt`` and ``config.json``.  The
saved config records the resolved values after applying command-line overrides.
"""

