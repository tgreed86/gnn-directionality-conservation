TARGET_TYPES = ("increment", "rate")
LEGACY_TARGET_TYPE_ALIASES = {"next": "increment"}


def canonical_target_type(target_type: object) -> str:
    """Return the current target name, accepting legacy dataset metadata."""
    value = str(target_type)
    value = LEGACY_TARGET_TYPE_ALIASES.get(value, value)
    if value not in TARGET_TYPES:
        choices = ", ".join(repr(item) for item in TARGET_TYPES)
        raise ValueError(
            f"Unsupported target_type {target_type!r}; expected {choices}."
        )
    return value


